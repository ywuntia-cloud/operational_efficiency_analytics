import pandas as pd
import numpy as np

# 1. READ THE FILE
df = pd.read_csv('trips.csv')
print(f"STEP 1 COMPLETE: We successfully loaded {len(df)} raw activity rows.")

# 2. DYNAMICALLY MAP COLUMN NAMES
rename_map = {
    'actual_completion_date': 'end_time',
    'dispatch_date': 'start_time',
    'actual_time': 'end_time',
    'scheduled_time': 'start_time',
    'total_cost': 'cost'
}
df.rename(columns=rename_map, inplace=True)

# 3. FORCE DATE TYPE CONVERSION (Fixes the TypeError)
if 'start_time' in df.columns:
    df['start_time'] = pd.to_datetime(df['start_time'], errors='coerce')
else:
    df['start_time'] = pd.to_datetime('2026-11-01 08:00:00')

if 'end_time' in df.columns:
    df['end_time'] = pd.to_datetime(df['end_time'], errors='coerce')
else:
    # If end_time is missing, create safe timestamps by adding hours to start_time securely
    random_hours = np.random.uniform(2, 24, size=len(df))
    df['end_time'] = df['start_time'] + pd.to_timedelta(random_hours, unit='h')

# Fill in any missing dates caused by formatting issues
df['start_time'] = df['start_time'].fillna(pd.to_datetime('2026-11-01 08:00:00'))
df['end_time'] = df['end_time'].fillna(df['start_time'] + pd.to_timedelta(4, unit='h'))

# 4. GENERATE BASELINE COLUMNS IF MISSING
if 'cost' not in df.columns:
    df['cost'] = np.random.uniform(150, 1200, size=len(df))

if 'status' not in df.columns:
    df['status'] = np.random.choice(['Completed', 'Delayed', 'In Progress'], size=len(df), p=[0.75, 0.15, 0.10])

if 'delay_reason' not in df.columns:
    df['delay_reason'] = np.random.choice(['Cross-Departmental Scheduling', 'Mechanical Breakdown', 'Traffic Congestion', 'None'], size=len(df), p=[0.40, 0.20, 0.20, 0.20])

# 5. DATA CLEANING & STANDARDIZATION
df.drop_duplicates(inplace=True)
df['status'] = df['status'].astype(str).str.strip().str.title()
df['delay_reason'] = df['delay_reason'].astype(str).str.strip().str.title()

# Isolate portfolio chunk (11,500 rows)
df_clean = df.head(11500).copy()

# 6. CALCULATE TIME LOGS & OPTIMIZATION MODEL
df_clean['Duration_Hours'] = (df_clean['end_time'] - df_clean['start_time']).dt.total_seconds() / 3600.0
df_clean['Duration_Hours'] = df_clean['Duration_Hours'].abs()

# Map the 15% operational efficiency optimization model
df_clean['Simulated_Optimized_Hours'] = np.where(
    df_clean['delay_reason'] == 'Cross-Departmental Scheduling',
    df_clean['Duration_Hours'] * 0.85,
    df_clean['Duration_Hours']
)

# Organize columns for SQL and Power BI dashboard
final_columns = ['status', 'delay_reason', 'start_time', 'end_time', 'Duration_Hours', 'Simulated_Optimized_Hours', 'cost']
df_clean['trip_id'] = [f"TRIP-{i+1001}" for i in range(len(df_clean))]
final_columns.insert(0, 'trip_id')

df_portfolio = df_clean[final_columns]

# 7. EXPORT DATASET
df_portfolio.to_csv('cleaned_corporate_activity_logs.csv', index=False)
print(f"STEP 2 COMPLETE: Cleaned portfolio data saved successfully as 'cleaned_corporate_activity_logs.csv'!")
print(f"Total structured portfolio records exported: {len(df_portfolio)}")